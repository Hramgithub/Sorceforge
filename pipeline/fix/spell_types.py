"""Reduce spell categories to 14 types (R-66).

    python pipeline/fix/spell_types.py [--write]
"""
import glob
import json
import sys

sys.stdout.reconfigure(encoding="utf-8")

TYPES = {
    "Атака": ["атака", "ментальная атака", "атака/порошок", "атака против нежити", "атака/обездвиживание",
              "яд/атака", "свет/атака", "кража жизни", "магическая кража"],
    "Проклятие": ["проклятие", "калечащее проклятие", "проклятие/зачарование", "проклятие/изгнание",
                  "проклятие/иллюзия", "проклятие/лечение"],
    "Связь": ["связь", "сон/связь", "связь/видение", "связь/контроль духа", "связь/разум"],
    "Вызов и изгнание": ["вызов/изгнание", "вызов/божество", "изгнание", "изгнание божества",
                         "изгнание/экзорцизм", "экзорцизм", "Страна грёз/рассеивание"],
    "Призыв и укрощение": ["призыв/укрощение", "призыв"],
    "Контроль и разум": ["контроль", "контроль животного", "народная/контроль", "разум", "влияние", "память",
                         "иллюзия/маскировка", "усиление социального влияния"],
    "Защита": ["защита", "барьер", "народная/барьер", "оберег", "охрана места", "старшая защита", "знак/защита",
               "защита предмета/места", "защита разума", "защита/изгнание", "защита/контрмагия",
               "бессмертие/защита", "снятие чар", "обезвреживание", "сокрытие"],
    "Зачарование": ["зачарование", "зачарование оружия", "зачарование/призыв", "зачарование/связь"],
    "Врата и путешествия": ["врата", "врата/видение", "врата/наблюдение", "перемещение", "путешествие",
                            "духовное путешествие", "Страна грёз/путешествие", "время"],
    "Создание существ": ["создание зомби", "создание зомби/вариант", "создание существа", "некромантия"],
    "Изменение тела": ["изменение тела", "изменение плоти", "трансформация/яд", "народная/трансформация",
                       "маскировка", "усиление", "самосовершенствование"],
    "Познание": ["выявление", "поиск", "прорицание", "сон/прорицание", "усиление знания", "усиление чувств"],
    "Природа и стихии": ["стихийное воздействие", "окружающая среда", "народная/морская магия"],
    "Исцеление": ["лечение", "народная/лечение", "обезболивание", "восстановление магии"],
}
MAP = {old: new for new, olds in TYPES.items() for old in olds}


def main():
    write = "--write" in sys.argv
    missing, counts = set(), {}
    for f in sorted(glob.glob("kb/spells/*.json")):
        d = json.load(open(f, encoding="utf-8"))
        old = d.get("category")
        new = MAP.get(old, old if old in TYPES else None)
        if new is None:
            missing.add(old)
            continue
        counts[new] = counts.get(new, 0) + 1
        if write and new != old:
            d["category"] = new
            with open(f, "w", encoding="utf-8", newline="\n") as fh:
                fh.write(json.dumps(d, ensure_ascii=False, indent=2) + "\n")
    for k, v in sorted(counts.items(), key=lambda x: -x[1]):
        print(v, k)
    print("unmapped:", missing or "none")


if __name__ == "__main__":
    main()
